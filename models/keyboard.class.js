/**
 * Represents the current state of keyboard keys being pressed.
 * Each property corresponds to a specific key and is set to `true` when pressed, `false` otherwise.
 */
class Keyboard {
  /**
   * @property {boolean} LEFT - Indicates if the left arrow key is pressed.
   */
  LEFT = false;

  /**
   * @property {boolean} RIGHT - Indicates if the right arrow key is pressed.
   */
  RIGHT = false;

  /**
   * @property {boolean} UP - Indicates if the up arrow key is pressed.
   */
  UP = false;

  /**
   * @property {boolean} DOWN - Indicates if the down arrow key is pressed.
   */
  DOWN = false;

  /**
   * @property {boolean} SPACE - Indicates if the spacebar key is pressed.
   */
  SPACE = false;

  /**
   * @property {boolean} W - Indicates if the "W" key is pressed.
   */
  W = false;

  /**
   * @property {boolean} A - Indicates if the "A" key is pressed.
   */
  A = false;

  /**
   * @property {boolean} S - Indicates if the "S" key is pressed.
   */
  S = false;

  /**
   * @property {boolean} D - Indicates if the "D" key is pressed.
   */
  D = false;

  /**
   * @property {boolean} F - Indicates if the "F" key is pressed.
   */
  F = false;
}
